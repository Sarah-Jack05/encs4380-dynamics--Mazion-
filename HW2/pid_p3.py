import matplotlib.pyplot as plt
from pyscript import document, display, when
from js import navigator
from pid_core_p2_p3 import simulate_pid_digital
from pid_core import compute_metrics

DT = 0.005
PLANT = {"K": 1.0, "tau": 1.0}
U_MAX = 10.0
SETPOINT = 1.0
SWEEP_TS = [0.005, 0.01, 0.02, 0.05, 0.1, 0.15, 0.2, 0.3, 0.4, 0.5]

COPY_LABEL = document.getElementById("p3-copy").innerText

ARDUINO_TEMPLATE = """// Digital PID loop (generated by the toolkit)
const float Kp = @KP@;
const float Ki = @KI@;
const float Kd = @KD@;
const unsigned long TS_MS = @TSMS@;       // sampling time in ms
const float Ts = TS_MS / 1000.0;          // sampling time in seconds
const float U_MIN = @UMIN@;
const float U_MAX = @UMAX@;
const float setpoint = @SP@;

float integral = 0.0;
float prevError = 0.0;
bool firstSample = true;
unsigned long lastTime = 0;

float readSensor() {
  return analogRead(A0) * (5.0 / 1023.0); // TODO: convert to your units
}

void writeActuator(float u) {
  // TODO: send u to your actuator (for example analogWrite)
}

void setup() {
  Serial.begin(9600);
}

void loop() {
  unsigned long now = millis();
  if (now - lastTime >= TS_MS) {
    lastTime += TS_MS;

    float y = readSensor();
    float error = setpoint - y;

    float integralNew = integral + error * Ts;
    float derivative = firstSample ? 0.0 : (error - prevError) / Ts;

    float uRaw = Kp * error + Ki * integralNew + Kd * derivative;
    float u = constrain(uRaw, U_MIN, U_MAX);
@AW@
    prevError = error;
    firstSample = false;
    writeActuator(u);
  }
}
"""

def build_arduino_code(kp, ki, kd, ts_eff, anti_windup):
    if anti_windup:
        aw = "    if (uRaw == u) integral = integralNew;   // anti-windup: stop integrating when saturated"
    else:
        aw = "    integral = integralNew;                  // anti-windup OFF"
    ts_ms = int(round(ts_eff * 1000))
    code = ARDUINO_TEMPLATE
    code = code.replace("@KP@", f"{kp:.3f}").replace("@KI@", f"{ki:.3f}").replace("@KD@", f"{kd:.3f}")
    code = code.replace("@TSMS@", str(ts_ms))
    code = code.replace("@UMIN@", f"{-U_MAX:.1f}").replace("@UMAX@", f"{U_MAX:.1f}")
    code = code.replace("@SP@", f"{SETPOINT:.1f}").replace("@AW@", aw)
    return code

def update_p3(event=None):
    ts = float(document.getElementById("p3-ts-slider").value)
    kp = float(document.getElementById("p3-kp").value)
    ki = float(document.getElementById("p3-ki").value)
    kd = float(document.getElementById("p3-kd").value)
    aw = bool(document.getElementById("p3-aw").checked)

    document.getElementById("p3-ts-val").innerText = f"{ts:.3f}"
    document.getElementById("p3-kp-val").innerText = f"{kp:.1f}"
    document.getElementById("p3-ki-val").innerText = f"{ki:.1f}"
    document.getElementById("p3-kd-val").innerText = f"{kd:.1f}"

    t, r, y, u = simulate_pid_digital("first_order", PLANT, kp, ki, kd, ts,
                                      anti_windup=aw, setpoint=SETPOINT,
                                      u_min=-U_MAX, u_max=U_MAX, dt=DT)
    m = compute_metrics(t, y, SETPOINT)
    document.getElementById("p3-os").innerText = str(m["overshoot"])
    document.getElementById("p3-ts").innerText = str(m["settling_time"])
    document.getElementById("p3-ess").innerText = str(m["ss_error"])

    # Plot 1: output y(t) and the stair-step control signal u[k]
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(8, 6), sharex=True)
    ax1.plot(t, r, 'k--', label="Setpoint r(t)")
    ax1.plot(t, y, 'b-', linewidth=2, label="Output y(t)")
    ax1.set_ylabel("Output y(t)")
    ax1.set_title("Digital PID, Ts = " + f"{ts:.3f} s")
    ax1.legend(loc="lower right")
    ax1.grid(True, alpha=0.3)

    ax2.step(t, u, where='post', color='g', linewidth=2, label="Control u[k]")
    ax2.axhline(U_MAX, color='r', linestyle='--', label="Actuator limit")
    ax2.axhline(-U_MAX, color='r', linestyle='--')
    ax2.set_xlabel("Time (s)")
    ax2.set_ylabel("Control u")
    ax2.legend(loc="upper right")
    ax2.grid(True, alpha=0.3)
    plt.tight_layout()
    document.getElementById("p3-plot").innerHTML = ""
    display(fig, target="p3-plot")
    plt.close(fig)

    # Plot 2: how performance changes as Ts grows (same gains, same anti-windup)
    overs, errs = [], []
    for ts_i in SWEEP_TS:
        _, _, y_i, _ = simulate_pid_digital("first_order", PLANT, kp, ki, kd, ts_i,
                                            anti_windup=aw, setpoint=SETPOINT,
                                            u_min=-U_MAX, u_max=U_MAX, dt=DT)
        m_i = compute_metrics(t, y_i, SETPOINT)
        overs.append(m_i["overshoot"])
        errs.append(m_i["ss_error"])

    fig2, (bx1, bx2) = plt.subplots(2, 1, figsize=(8, 5), sharex=True)
    bx1.plot(SWEEP_TS, overs, 'o-', color='tab:orange')
    bx1.axvline(ts, color='gray', linestyle=':')
    bx1.set_ylabel("Overshoot (%)")
    bx1.set_title("Performance vs sampling time Ts")
    bx1.grid(True, alpha=0.3)
    bx2.plot(SWEEP_TS, errs, 'o-', color='tab:red')
    bx2.axvline(ts, color='gray', linestyle=':', label="current Ts")
    bx2.set_xlabel("Sampling time Ts (s)")
    bx2.set_ylabel("Steady-state error")
    bx2.legend(loc="upper left")
    bx2.grid(True, alpha=0.3)
    plt.tight_layout()
    document.getElementById("p3-perf-plot").innerHTML = ""
    display(fig2, target="p3-perf-plot")
    plt.close(fig2)

    # Arduino code for the current gains (Ts is rounded to a multiple of dt, like in the simulation)
    steps = max(1, round(ts / DT))
    document.getElementById("p3-code").textContent = build_arduino_code(kp, ki, kd, steps * DT, aw)
    document.getElementById("p3-copy").innerText = COPY_LABEL

@when("input", "#p3-ts-slider, #p3-kp, #p3-ki, #p3-kd")
def on_p3_slider(event):
    update_p3()

@when("change", "#p3-aw")
def on_p3_aw(event):
    update_p3()

@when("click", "#p3-copy")
def on_p3_copy(event):
    navigator.clipboard.writeText(document.getElementById("p3-code").textContent)
    document.getElementById("p3-copy").innerText = "Copied!"

update_p3()