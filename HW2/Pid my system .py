U_MIN, U_MAX = 0.0, 100.0          # PWM command range in %

SPEC = {                            # single source of truth: the page table is built from this
    "max_os": 10.0,                 # overshoot, %
    "max_ts": 0.30,                 # settling time (2 % band), s
    "max_ess": 1.0,                 # steady-state error, % of setpoint
    "zeta_lo": 0.6,                 # damping range from the lecture
    "zeta_hi": 0.8,
}

SPEC_WHY = {
    "Overshoot": "Speed overshoot on a slick floor means wheel slip and position error (M5: stop within 10 mm).",
    "Settling time": "A cell is 180 mm: the speed must settle fast, or the robot never reaches a steady speed inside one cell.",
    "Steady-state error": "A speed error is a distance error: 1 % too fast over 5 cells is about 9 mm.",
    "PWM within 0-100 %": "The motor driver cannot output more than 100 % (or reverse here): beyond that the controller loses control.",
    "Damping 0.6 to 0.8": "Practical range from the lecture: fast enough without ringing.",
}


# ------------------------- design maths -------------------------
def design_pi(K, tau, zeta, t_settle):
    """PI design for the first-order plant K/(tau*s+1) from the closed-loop characteristic equation
         tau*s^2 + (1 + K*Kp)*s + K*Ki = 0
       wn = sqrt(K*Ki/tau), zeta = (1+K*Kp)/(2*sqrt(tau*K*Ki)), settling time (2 %) ~ 4/(zeta*wn)."""
    wn = 4.0 / (zeta * t_settle)
    Ki = tau * wn ** 2 / K
    Kp = (2 * zeta * wn * tau - 1) / K
    note = ""
    if Kp < 0:                      # design asks for a slower loop than the plant itself
        Kp = 0.0
        Ki = 1.0 / (4 * zeta ** 2 * tau * K)
        wn = float(np.sqrt(K * Ki / tau))
        note = "Requested settling time is slower than the motor allows with a P term: Kp set to 0 (I-only)."
    return {"wn": wn, "Kp": Kp, "Ki": Ki, "Kd": 0.0, "note": note}


def actual_zeta(K, tau, Kp, Ki):
    return (1 + K * Kp) / (2 * np.sqrt(tau * K * Ki))


def evaluate(K, tau, r, gains):
    """Run the shared closed-loop solver with the 0-100 % PWM limit and judge each part of the spec."""
    params = {"K": K, "tau": tau}
    t_end = max(3.0, 20 * tau)
    t, rr, y, u = simulate_pid("first_order", params, gains["Kp"], gains["Ki"], gains["Kd"],
                               setpoint=r, u_min=U_MIN, u_max=U_MAX, dt=0.002, t_end=t_end)
    m = compute_metrics(t, y, r)
    zeta = actual_zeta(K, tau, gains["Kp"], gains["Ki"])
    u0_unclipped = gains["Kp"] * r  # PWM demanded at the instant of the step

    ts_val = m["settling_time"]
    ess_pct = 100.0 * m["ss_error"] / abs(r) if r != 0 else 0.0
    saturated = bool(u.max() >= U_MAX - 1e-6 or u.min() <= U_MIN + 1e-6)

    checks = [
        ("Overshoot", f"{m['overshoot']} %", f"&le; {SPEC['max_os']} %", m["overshoot"] <= SPEC["max_os"]),
        ("Settling time", f"{ts_val} s" if isinstance(ts_val, float) else str(ts_val),
         f"&le; {SPEC['max_ts']} s", isinstance(ts_val, float) and ts_val <= SPEC["max_ts"]),
        ("Steady-state error", f"{ess_pct:.2f} %", f"&le; {SPEC['max_ess']} %", ess_pct <= SPEC["max_ess"]),
        ("PWM within 0-100 %", f"demand at step {u0_unclipped:.1f} %, peak {u.max():.1f} %",
         "0 to 100 %, no clipping", not saturated),
        ("Damping 0.6 to 0.8", f"{zeta:.2f}", f"{SPEC['zeta_lo']} to {SPEC['zeta_hi']}",
         SPEC["zeta_lo"] - 1e-6 <= zeta <= SPEC["zeta_hi"] + 1e-6),
    ]
    return {"t": t, "r": rr, "y": y, "u": u, "metrics": m, "zeta": zeta,
            "u0": u0_unclipped, "checks": checks}


def arduino_code(g, Ts_ms=10):
    """Arduino speed loop with the same structure as the simulator (conditional-integration anti-windup)."""
    return f"""// PID speed loop for one drive motor (generated by the My System page)
const float Kp = {g['Kp']:.4f}f;
const float Ki = {g['Ki']:.4f}f;
const float Kd = {g['Kd']:.4f}f;
const float Ts = {Ts_ms / 1000.0:.3f}f;          // sample time in seconds ({Ts_ms} ms)
const float U_MIN = {U_MIN:.0f}.0f, U_MAX = {U_MAX:.0f}.0f;   // PWM in %

float integral = 0.0f, prevError = 0.0f;
unsigned long lastTick = 0;

float pidStep(float setpoint, float measured) {{
  float error = setpoint - measured;
  float derivative = (error - prevError) / Ts;
  float uRaw = Kp * error + Ki * integral + Kd * derivative;
  float u = constrain(uRaw, U_MIN, U_MAX);
  if (uRaw == u) integral += error * Ts;          // anti-windup: stop integrating while saturated
  prevError = error;
  return u;
}}

void loop() {{
  if (millis() - lastTick >= {Ts_ms}) {{
    lastTick += {Ts_ms};
    float speed = readSpeedMmPerS();              // from the encoder (your function)
    float u = pidStep(targetSpeed, speed);        // 0..100 %
    setMotorPwmPercent(u);                        // your function (maps % to the PWM duty)
  }}
}}"""


# ------------------------- page (PyScript) -------------------------
def _num(el_id, default):
    try:
        return float(document.getElementById(el_id).value)
    except (TypeError, ValueError):
        return default


def build_spec_table():
    rows = (
        ("Overshoot", f"&le; {SPEC['max_os']} %"),
        ("Settling time", f"&le; {SPEC['max_ts']} s (2 % band)"),
        ("Steady-state error", f"&le; {SPEC['max_ess']} % of the setpoint"),
        ("PWM within 0-100 %", "no clipping"),
        ("Damping 0.6 to 0.8", "lecture range"),
    )
    html = ""
    for name, limit in rows:
        html += f"<tr><td>{name}</td><td>{limit}</td><td>{SPEC_WHY[name]}</td></tr>"
    document.getElementById("ms-spec-body").innerHTML = html


def update_my_system(event=None):
    K = _num("ms-k", 2.0)
    tau = _num("ms-tau", 0.10)
    r = _num("ms-r", 60.0)
    zeta_d = _num("ms-zeta", 0.7)
    t_des = _num("ms-tdes", 0.25)
    if K <= 0 or tau <= 0 or zeta_d <= 0 or t_des <= 0:
        document.getElementById("ms-status").innerHTML = "<span class='fail'>K, tau, zeta and settling target must be positive.</span>"
        return

    g = design_pi(K, tau, zeta_d, t_des)
    res = evaluate(K, tau, r, g)
    m = res["metrics"]

    document.getElementById("my-k").innerText = f"{K:g} (mm/s per 1 % PWM)"
    document.getElementById("my-tau").innerText = f"{tau:g}"
    src = document.getElementById("ms-source-in").value.strip() or "not stated"
    document.getElementById("my-source").innerText = src
    document.getElementById("ms-wn").innerText = f"{g['wn']:.2f}"
    document.getElementById("my-kp").innerText = f"{g['Kp']:.4f}"
    document.getElementById("my-ki").innerText = f"{g['Ki']:.4f}"
    document.getElementById("my-kd").innerText = f"{g['Kd']:.1f}"
    document.getElementById("ms-zeta-out").innerText = f"{res['zeta']:.2f}"
    document.getElementById("ms-u0").innerText = f"{res['u0']:.1f}"
    document.getElementById("ms-tr").innerText = str(m["rise_time"])
    document.getElementById("ms-os").innerText = str(m["overshoot"])
    document.getElementById("ms-ts").innerText = str(m["settling_time"])
    document.getElementById("ms-ess").innerText = str(m["ss_error"])

    rows = ""
    for name, value, limit, ok in res["checks"]:
        cls = "pass" if ok else "fail"
        word = "PASS" if ok else "FAIL"
        rows += f"<li><span class='{cls}'>{word}</span> {name}: {value} (limit {limit})</li>"
    document.getElementById("ms-checks").innerHTML = rows

    all_ok = all(c[3] for c in res["checks"])
    msg = "PASS! All spec parts met." if all_ok else "Some spec parts fail: change gains, setpoint or design targets."
    cls = "pass" if all_ok else "fail"
    if g["note"]:
        msg += " " + g["note"]
    document.getElementById("ms-status").innerHTML = f"<span class='{cls}'>{msg}</span>"

    document.getElementById("my-code").innerText = arduino_code(g)

    import matplotlib.pyplot as plt  # imported here so the maths above also runs without matplotlib
    t, rr, y, u = res["t"], res["r"], res["y"], res["u"]
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(8, 6), sharex=True)
    ax1.plot(t, rr, 'k--', label="Setpoint r(t)")
    ax1.plot(t, y, 'b-', linewidth=2, label="Wheel speed y(t)")
    ax1.axhline(r * (1 + SPEC["max_os"] / 100.0), color='r', linestyle=':', label="Max allowed overshoot")
    ax1.axvline(SPEC["max_ts"], color='orange', linestyle=':', label="Settling-time limit")
    ax1.set_xlim(0, min(t[-1], max(1.5, 5 * SPEC["max_ts"])))
    ax1.set_ylabel("Speed (mm/s)")
    ax1.set_title("My System: closed-loop step response")
    ax1.legend(loc="lower right")
    ax1.grid(True, alpha=0.3)

    ax2.plot(t, u, 'g-', linewidth=2, label="PWM command u(t)")
    ax2.axhline(U_MAX, color='r', linestyle='--', label="PWM limits (0 and 100 %)")
    ax2.axhline(U_MIN, color='r', linestyle='--')
    ax2.set_xlabel("Time (s)")
    ax2.set_ylabel("PWM (%)")
    ax2.legend(loc="upper right")
    ax2.grid(True, alpha=0.3)
    plt.tight_layout()
    document.getElementById("my-plot").innerHTML = ""
    display(fig, target="my-plot")
    plt.close(fig)


if document is not None:
    @when("input", "#ms-k, #ms-tau, #ms-r, #ms-zeta, #ms-tdes, #ms-source-in")
    def on_ms_input(event):
        update_my_system()

    @when("click", "#ms-copy-btn")
    def on_ms_copy(event):
        from pyscript import window
        window.navigator.clipboard.writeText(document.getElementById("my-code").innerText)
        document.getElementById("ms-copy-btn").innerText = "Copied!"

    build_spec_table()
    update_my_system()
